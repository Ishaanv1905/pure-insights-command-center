// Profiles the RAW case-study CSV (before it touches the server) and writes
// docs/data-quality.md. Run: npm run data-quality
//
// It runs every row through the same processReading() the server uses, so the
// report and the running system can never disagree about what is a defect.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv } from '../../feeder/csv.js';
import { rowToReading } from '../../feeder/feeder.js';
import { processReading, COST_EXCLUDING_FLAGS } from '../src/services/readingValidator.js';
import { findUsageMismatches } from '../src/services/usageMismatch.js';
import { loadConfig } from '../src/config/index.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const csvPath = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(root, 'data', 'Case_Study_3_Pure_Insights_Monitoring.csv');
const outPath = path.join(root, 'docs', 'data-quality.md');

const config = loadConfig();
const rows = parseCsv(fs.readFileSync(csvPath, 'utf8'));
const results = rows.map((row) => processReading(rowToReading(row), config.alerts));
const accepted = results.filter((r) => r.ok).map((r) => r.reading);
const rejected = results.filter((r) => !r.ok);

const count = (pred) => accepted.filter(pred).length;
const has = (flag) => (r) => r.flags.includes(flag);
const pct = (n, total = rows.length) => `${((100 * n) / total).toFixed(1)}%`;
const ids = new Set(rows.map((r) => r.report_id));
const perReport = {};
for (const r of rows) perReport[r.report_id] = (perReport[r.report_id] ?? 0) + 1;
const readingsPerReport = [...new Set(Object.values(perReport))];

const ownerRaw = {};
for (const r of accepted.filter(has('ORPHANED')))
  ownerRaw[r.owner_email_raw ?? '(missing)'] = (ownerRaw[r.owner_email_raw ?? '(missing)'] ?? 0) + 1;
const statusCounts = {};
for (const r of accepted) statusCounts[r.last_refresh_status] = (statusCounts[r.last_refresh_status] ?? 0) + 1;
const negatives = accepted.filter(has('NEGATIVE_CREDITS')).map((r) => r.snowflake_credits_consumed);
const latencies = accepted.map((r) => r.avg_load_time_sec);
const at15 = count((r) => r.avg_load_time_sec === config.alerts.latencyThresholdSec);

// Defect (d): the same function the API uses for the Cost page
const valid = accepted
  .filter((r) => !r.flags.some((f) => COST_EXCLUDING_FLAGS.includes(f)))
  .map((r, i) => ({ ...r, id: i + 1, received_at: '' }));
const mismatch = findUsageMismatches(valid, { iqrK: config.cost.mismatchIqrK });
const ms = mismatch.summary;
const worst = mismatch.readings.filter((m) => m.direction === 'high_cost_low_usage')[0];
const cheapest = mismatch.readings.filter((m) => m.direction === 'low_cost_high_usage')[0];
const zeroViews = accepted.filter(has('ZERO_VIEWS'));

const md = `# Data Quality Report

_Generated by \`npm run data-quality\` from \`${path.basename(csvPath)}\` on ${new Date().toISOString().slice(0, 10)}._
_Every row is run through the same \`processReading()\` function the server uses, so these numbers match what the running app shows._

## Shape of the data

| Item | Value |
|---|---|
| Rows | ${rows.length} |
| Columns | ${Object.keys(rows[0]).length} (${Object.keys(rows[0]).join(', ')}) |
| Distinct reports | ${ids.size} |
| Readings per report | ${readingsPerReport.join(', ')} |
| Row order | round-robin: row *i* belongs to RPT_${200} + (*i* mod ${ids.size}) |
| Timestamp column | none (the server stamps \`received_at\` on arrival) |
| Rows rejected as malformed | ${rejected.length} |

**Interpretation:** the file is ${readingsPerReport[0]} successive snapshots of the same ${ids.size} reports, not ${rows.length} different reports. The app therefore stores every row as a *reading* (history) and keeps the latest reading per report as its *current state*. Values such as the owner and the refresh status change between snapshots of the same report, so "current state" always means "latest reading".

## Planted defects and how each is handled

| # | Defect | Rows affected | Handling | Why |
|---|---|---|---|---|
| 1 | Orphaned owner | ${count(has('ORPHANED'))} (${pct(count(has('ORPHANED')))}): ${Object.entries(ownerRaw)
  .map(([k, v]) => `${v} \`${k}\``)
  .join(
    ', ',
  )} | Accepted. \`owner_email\` normalized to null, raw text kept in \`owner_email_raw\`, flag \`ORPHANED\`. Listed on the Orphaned page; admins can assign an owner. | Orphaned reports are something the dashboard must *show* (Task 1). Deleting them would hide the problem. |
| 2 | Negative Snowflake credits | ${negatives.length} (${pct(negatives.length)}), minimum ${Math.min(...negatives)} | Accepted and stored unchanged, flag \`NEGATIVE_CREDITS\`. **Excluded from all cost calculations.** | A negative consumption is impossible; using it would understate cost. Keeping the raw row preserves the audit trail. |
| 3 | Load latency spikes | ${count(has('HIGH_LATENCY'))} (${pct(count(has('HIGH_LATENCY')))}) above ${config.alerts.latencyThresholdSec}s; max ${Math.max(...latencies)}s; ${at15} rows at exactly ${config.alerts.latencyThresholdSec}.0s | Accepted, flag \`HIGH_LATENCY\`. Drives the latency alert rule. Exactly ${config.alerts.latencyThresholdSec}.0s is **not** a breach ("exceeds" = strictly greater). Above ${config.alerts.latencyCriticalSec}s the alert is critical. | These are the alert triggers (Task 2). Because ~${pct(count(has('HIGH_LATENCY')))} of rows breach, alerts fire on *state change* with a cooldown, not on every row. |
| 4 | Usage vs AWS cost discrepancy | ${ms.mismatched_readings} of ${ms.readings_checked} valid readings (${ms.reports_affected} reports): ${ms.high_cost_low_usage} high cost / low usage, ${ms.low_cost_high_usage} low cost / high usage, ${ms.cost_with_no_usage} cost with zero views | Not modified. Each reading's AWS cost per active view and per peak concurrent user is compared with Tukey fences learned from all readings (log scale, k = ${config.cost.mismatchIqrK}). Out-of-line readings and the reports they belong to are listed on the Cost page (\`GET /api/cost/usage-mismatch\`). | Hosting cost does not follow usage at all: correlation with views **r = ${mismatch.correlation.views_vs_aws_cost}**, with peak users **r = ${mismatch.correlation.peak_users_vs_aws_cost}**. Normal AWS cost per view is about $${mismatch.fences_usd.per_view.median}; readings above $${mismatch.fences_usd.per_view.high} or below $${mismatch.fences_usd.per_view.low} are flagged. Most extreme: ${worst.report_id} with ${worst.monthly_active_views} views for $${worst.aws_hosting_cost_usd} ($${worst.aws_cost_per_view_usd} per view), versus ${cheapest.report_id} with ${cheapest.monthly_active_views} views for $${cheapest.aws_hosting_cost_usd}. |

## Other findings (not listed in the brief)

| Finding | Rows | Handling |
|---|---|---|
| \`last_refresh_status\` values | ${Object.entries(statusCounts)
  .map(([k, v]) => `${k} ${v}`)
  .join(
    ', ',
  )} | FAILED and TIMED_OUT count as refresh failures (flag \`REFRESH_FAILED\`, alert). UNKNOWN is flagged \`REFRESH_UNKNOWN\` and shown as a warning but does not alert, because "no information" is not evidence of failure. |
| Zero monthly views | ${zeroViews.length} (${zeroViews.map((r) => r.report_id).join(', ')}) | Flag \`ZERO_VIEWS\`. Cost per view uses ratio-of-sums across readings, so a zero never causes a division by zero. These rows still cost money, which is itself worth surfacing. |
| Owner changes between snapshots | most reports | Expected with snapshot data; the current owner is the latest reading's owner unless an admin assigned one. |

## Rules for anything else that arrives

| Situation | Response |
|---|---|
| Missing \`report_id\`, unknown status, a number sent as text, NaN, fractional count | **Rejected** with 400 and every error listed. The payload is saved in \`rejected_payloads\` and shown on the Data Quality page. |
| Any other negative numeric value | Accepted, flag \`NEGATIVE_METRIC\`, excluded from cost math. |
| Same \`Idempotency-Key\` sent twice | Second request returns 200 \`duplicate: true\` and stores nothing. |
`;

fs.writeFileSync(outPath, md);
console.log(
  `Wrote ${path.relative(root, outPath)}  (${rows.length} rows, ${accepted.length} accepted, ${rejected.length} rejected)`,
);
